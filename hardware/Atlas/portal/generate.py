"""Regenerate the offline portal header: python portal/generate.py [--check]."""
import gzip
from pathlib import Path
import sys

root = Path(__file__).resolve().parent
data = gzip.compress((root / "index.html").read_bytes(), compresslevel=9, mtime=0)
lines = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
header = ("// Generated by portal/generate.py; edit portal/index.html, not this file.\n"
          "#pragma once\n#include <Arduino.h>\n"
          "static const uint8_t SetupPageGzip[] PROGMEM = {\n    "
          + ",\n    ".join(lines) + "\n};\n")
target = root.parent / "src" / "SetupPage.generated.h"
if "--check" in sys.argv:
    if not target.exists() or target.read_text(encoding="utf-8") != header:
        raise SystemExit("Portal header is stale. Run python portal/generate.py.")
else:
    target.write_text(header, encoding="utf-8", newline="\n")
print(f"Portal: {len(data)} bytes gzip; header {'checked' if '--check' in sys.argv else 'generated'}.")
